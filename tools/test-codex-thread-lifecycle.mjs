import { VESPER_DESIRE_SESSION_CONFIG } from '../lib/desire/routing.js';
import assert from 'node:assert/strict';
import {syncCodexThread,createConnectionQueue,resumeCodexThread} from '../lib/codex-thread-lifecycle.ts';
const calls=[];
let hasThread=false;
const start=async()=>{calls.push('start');hasThread=true;};
const resume=async()=>{calls.push('resume');};
const run=(newConnection,createIfMissing,instructionsChanged=true)=>syncCodexThread({hasThread,newConnection,createIfMissing,instructionsChanged,start,resume});
await run(true,false);
assert.deepEqual(calls,[], 'Opening a new conversation does not create a rollout-less thread');
await run(false,true);
assert.deepEqual(calls,['start'], 'First send creates with recalled instructions, never resumes an empty thread');
await run(false,true,false);
assert.deepEqual(calls,['start']);
await run(true,false,false);
assert.deepEqual(calls,['start','resume'], 'Existing history reconnects without replacement');
await assert.rejects(()=>syncCodexThread({hasThread:true,newConnection:true,createIfMissing:true,instructionsChanged:false,start,resume:async()=>{throw Error('no rollout found');}}));
assert.deepEqual(calls,['start','resume'],'A missing persisted rollout is never silently replaced');
const queue=createConnectionQueue();
let release;
const gate=new Promise(resolve=>{release=resolve;});
const order=[];
const first=queue(async()=>{order.push('initialize');await gate;order.push('ready');});
const second=queue(async()=>{order.push('send');});
await Promise.resolve();
assert.deepEqual(order,['initialize']);
release();await Promise.all([first,second]);
assert.deepEqual(order,['initialize','ready','send']);
await assert.rejects(queue(async()=>{throw Error('offline');}));
await queue(async()=>{order.push('retry');});
assert.equal(order.at(-1),'retry');
console.log('Lazy first-turn creation, preserved existing threads and serialized connection/retry passed');

const resumeCalls=[];
const snapshot={result:{thread:{id:'existing',turns:[]}}};
const rpc=async(method,params)=>{resumeCalls.push({method,params});return snapshot;};
assert.equal(await resumeCodexThread(rpc,'existing','context'),snapshot);
assert.deepEqual(resumeCalls,[{method:'thread/resume',params:{threadId:'existing',developerInstructions:'context',config:VESPER_DESIRE_SESSION_CONFIG}}]);
let attempts=0;
await assert.rejects(resumeCodexThread(async()=>{attempts++;throw Error('invalid params');},'existing','context'),/invalid params/);
assert.equal(attempts,1,'Failed resume must not retry without configuration and imply tools were refreshed');
console.log('Resume preserves configuration, does not send unsupported dynamicTools, and never silently downgrades');
