import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const objects = new Map();
const source = ts.transpileModule(fs.readFileSync('lib/codex-artifacts.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const adapterSource = ts.transpileModule(fs.readFileSync('lib/backend/media.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const adapter = {}; vm.runInNewContext(adapterSource, { exports: adapter });
const bucket = { put: async (key, bytes, metadata) => objects.set(key, { bytes: [...bytes], metadata }) };
const exports = {};
vm.runInNewContext(source, { exports, require: name => { if (name === './photo-album') return { registerPhotoSource: async () => {} }; assert.equal(name, './backend/services'); return { media: () => new adapter.MediaRepository(bucket) }; }, crypto: globalThis.crypto, TextEncoder, Uint8Array, atob, encodeURIComponent });
const send = (input, owner = 'private-owner') => exports.createChatFile(input, owner, 'https://example.test');
const first = await send({ name: 'hello.txt', text: '你好', mimeType: 'text/plain' });
assert.equal(first.size, 6); assert.equal(first.type, 'text/plain');
assert.deepEqual(objects.get(first.key).bytes, [...new TextEncoder().encode('你好')]);
assert.equal((await send({ name: 'hello.txt', text: '你好', mimeType: 'text/plain' })).key, first.key);
assert.notEqual((await send({ name: 'hello.txt', text: '你好', mimeType: 'text/plain' }, 'another-owner')).key, first.key);
const html = await send({ name: 'test.html', text: '<script>bad()</script>', mimeType: 'text/html' });
assert.equal(html.type, 'application/octet-stream');
assert.match(objects.get(html.key).metadata.httpMetadata.contentDisposition, /^attachment/);
const binary = await send({ name: 'bytes.bin', base64: 'AAEC/w==' });
assert.deepEqual(objects.get(binary.key).bytes, [0, 1, 2, 255]);
await assert.rejects(send({ name: 'bad.bin', base64: '!!!!' }));
await assert.rejects(send({ name: 'bad.txt', text: 'x', base64: 'AA==' }));
await assert.rejects(send({ name: 'large.txt', text: 'a'.repeat(8 * 1024 * 1024 + 1) }));
assert.equal(objects.size, 4);
console.log('Real file bytes, replay identity, owner separation, download headers and input limits passed');
