import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const database = new DatabaseSync(':memory:');
database.exec('CREATE TABLE vesper_memories(id TEXT PRIMARY KEY,user_id TEXT,character_id TEXT)');
const adapter = { prepare(sql) { let args=[]; return { bind(...values) { args=values; return this; }, async run() { return database.prepare(sql).run(...args); }, async all() { return { results: database.prepare(sql).all(...args) }; } }; }, async batch(statements) { for (const statement of statements) await statement.run(); } };
globalThis.vaultTestDB=adapter;
const source=readFileSync(new URL('../lib/memory-vault.ts',import.meta.url),'utf8').replace("import { ensureSchema, getDb } from '@/lib/db';",'const ensureSchema=async()=>{}; const getDb=()=>globalThis.vaultTestDB;');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const vault=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const owner={userId:'owner',characterId:'rowan'}, other={userId:'other',characterId:'rowan'};
const original={conversationId:'chat',messageId:'m1',role:'user',content:'  exact\n original text  ',createdAt:'2026-01-01T00:00:00Z',attachments:[{url:'https://example.test/file',name:'file.txt'}]};
const id=await vault.recordEvidence(owner,original);
assert.equal(await vault.recordEvidence(owner,original),id);
const corrected=await vault.recordEvidence(owner,{...original,content:'later change'});
assert.notEqual(corrected,id);
let evidence=await vault.evidenceFor(owner);assert.equal(evidence.length,2);assert.equal(evidence.find(x=>x.id===id).content,original.content);
assert.deepEqual(await vault.evidenceFor(other),[]);
database.prepare('INSERT INTO vesper_memories VALUES(?,?,?)').run('memory','owner','rowan');
await vault.linkEvidence(other,'memory',[id]);assert.deepEqual(await vault.evidenceFor(owner,'memory'),[]);
await vault.linkEvidence(owner,'memory',[id]);assert.equal((await vault.evidenceFor(owner,'memory'))[0].id,id);
assert.equal((await vault.evidenceIdsForMessages(owner,'chat',['m1'])).length,2);
assert.deepEqual(await vault.evidenceIdsForMessages(owner,'wrong',['m1']),[]);
console.log('Evidence immutability, idempotency, source links and owner isolation passed');

assert.equal((await vault.verifySharedEvidence(owner,[{conversation_id:'chat',message_id:'m1',quote:'exact\n original'}]))[0].created_at,original.createdAt);
await assert.rejects(vault.verifySharedEvidence(owner,[{conversation_id:'chat',message_id:'m1',quote:'invented quote'}]),/引用未在原始聊天/);
await assert.rejects(vault.verifySharedEvidence(other,[{conversation_id:'chat',message_id:'m1',quote:'exact'}]),/引用未在原始聊天/);
console.log('Shared memory quote validation and cross-owner rejection passed');
