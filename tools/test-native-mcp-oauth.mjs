import assert from 'node:assert/strict';
import { oauthCallbackDestination, nativeOAuthCode, NATIVE_OAUTH_CALLBACK } from '../lib/mcp-oauth-callback.ts';
const state = '00000000-0000-4000-8000-000000000001';
const incoming = new URL('https://vesper.r-vera.com/mcp/oauth/callback');
incoming.searchParams.set('native', '1');
incoming.searchParams.set('state', state);
incoming.searchParams.set('code', 'test-code');
incoming.searchParams.set('verifier', 'must-not-forward');
incoming.searchParams.set('redirect', 'https://untrusted.example');
const destination = oauthCallbackDestination(incoming);
assert.equal(destination.origin, new URL(NATIVE_OAUTH_CALLBACK).origin);
assert.equal(destination.protocol, 'vesper:');
assert.equal(destination.host, 'oauth');
assert.equal(nativeOAuthCode(destination.href, state), 'test-code');
assert.equal(destination.searchParams.has('verifier'), false);
assert.equal(destination.searchParams.has('redirect'), false);
assert.throws(() => nativeOAuthCode(destination.href, 'wrong-state'), /state mismatch/);
assert.throws(() => nativeOAuthCode(destination.href.replace('vesper:', 'https:'), state), /Unexpected/);
assert.throws(() => nativeOAuthCode(destination.href.replace('/oauth/callback', '/other'), state), /Unexpected/);
incoming.searchParams.delete('code');
incoming.searchParams.set('error', 'access_denied');
assert.throws(() => nativeOAuthCode(oauthCallbackDestination(incoming).href, state), /access_denied/);
incoming.searchParams.delete('error');
assert.throws(() => nativeOAuthCode(oauthCallbackDestination(incoming).href, state), /missing/);
incoming.searchParams.delete('native');
incoming.searchParams.set('state', 'ordinary-web-state');
const browser = oauthCallbackDestination(incoming);
assert.equal(browser.origin, incoming.origin);
assert.equal(browser.pathname, '/');
assert.equal(browser.searchParams.get('mcp-oauth'), '1');
incoming.searchParams.set('native', '0');
assert.equal(oauthCallbackDestination(incoming).protocol, 'https:');
console.log('Native OAuth: app/web routing, exact state, callback validation, cancellation and parameter allowlist passed');
